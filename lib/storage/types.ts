export type StorageDriver = "dev-filesystem" | "r2";

export interface SignedRequest {
  url: string;
  method: "PUT" | "GET";
  headers: Record<string, string>;
  expiresAt: Date;
}

/**
 * Private object storage. Callers must have authorized the request in the database
 * (RLS / trusted RPC) BEFORE asking for a signed URL. Keys come from the database.
 */
export interface StorageAdapter {
  readonly driver: StorageDriver;
  /** Short-lived URL that allows exactly one object key to be written, with a fixed type. */
  signUpload(key: string, contentType: string, byteSize: number, ttlSeconds: number): Promise<SignedRequest>;
  /** Short-lived URL to read one object. */
  signDownload(key: string, ttlSeconds: number): Promise<SignedRequest>;
  /** Facts about the stored object, or null if it does not exist. */
  inspect(key: string, headBytes: number): Promise<{ size: number; head: Uint8Array } | null>;
  /** Hex SHA-256 of the stored object. */
  sha256(key: string): Promise<string>;
}

// Must match the key format generated by public.begin_asset_upload().
const KEY_PATTERN =
  /^projects\/[0-9a-f-]{36}\/entities\/[0-9a-f-]{36}\/assets\/[0-9a-f-]{36}\/original\.(png|jpg)$/;

export function assertStorageKey(key: string): string {
  if (!KEY_PATTERN.test(key)) throw new Error("Refusing to sign an unexpected storage key.");
  return key;
}
