// SERVER ONLY. Runs one storyboard generation job: claims it, gathers the reference images
// that were recorded on the job, calls the provider, stores the result as a project asset
// (same checks as any upload), and records it. A failure records the error and leaves the
// shot's current frame alone.
import type { SupabaseClient } from "@supabase/supabase-js";
import { verifyStoredObject } from "../assets/validate";
import { assertConfiguredBucket, getStorage } from "../storage";
import { supabaseService } from "../supabase/server";
import { ProviderError, type ImageProvider, type ProviderImage } from "./provider";

type Db = SupabaseClient;

async function readAsset(db: Db, assetId: string): Promise<ProviderImage | null> {
  const { data: a } = await db.from("assets").select("storage_bucket, storage_key, mime_type, upload_status").eq("id", assetId).maybeSingle();
  if (!a || a.upload_status !== "ready") return null;
  assertConfiguredBucket(a.storage_bucket);
  const storage = await getStorage();
  const signed = await storage.signDownload(a.storage_key, 120);
  const res = await fetch(signed.url, { signal: AbortSignal.timeout(30_000) });
  if (!res.ok) return null;
  return { bytes: new Uint8Array(await res.arrayBuffer()), mime: a.mime_type === "image/jpeg" ? "image/jpeg" : "image/png" };
}

/** Store generated bytes as an asset on the storyboard's entity (as the requesting user). */
async function storeImage(user: Db, service: Db, entityId: string, name: string, img: ProviderImage): Promise<string> {
  if (img.mime !== "image/png" && img.mime !== "image/jpeg") throw new Error("Unexpected image type.");
  const { data, error } = await user.rpc("begin_asset_upload", { p_entity: entityId, p_file_name: name, p_mime_type: img.mime, p_byte_size: img.bytes.byteLength });
  if (error || !data?.[0]) throw new Error(error?.message ?? "Couldn't save the frame.");
  const row = data[0] as { asset_id: string; storage_bucket: string; storage_key: string };
  assertConfiguredBucket(row.storage_bucket);
  const storage = await getStorage();
  const up = await storage.signUpload(row.storage_key, img.mime, img.bytes.byteLength, 600);
  const put = await fetch(up.url, { method: up.method, headers: up.headers, body: Buffer.from(img.bytes) });
  if (!put.ok) {
    await service.rpc("fail_asset_upload", { p_asset: row.asset_id, p_reason: `Storage answered ${put.status}.` });
    throw new Error("Couldn't save the frame to storage.");
  }
  const check = verifyStoredObject({ mimeType: img.mime, byteSize: img.bytes.byteLength }, await storage.inspect(row.storage_key, 16));
  if (!check.ok) {
    await service.rpc("fail_asset_upload", { p_asset: row.asset_id, p_reason: check.error });
    throw new Error(check.error);
  }
  const { error: e2 } = await service.rpc("complete_asset_upload", {
    p_asset: row.asset_id, p_byte_size: check.value.byteSize, p_checksum_sha256: await storage.sha256(row.storage_key), p_mime_type: check.value.mimeType,
  });
  if (e2) throw new Error(e2.message);
  return row.asset_id;
}

export interface JobDeps {
  provider: ImageProvider;
  /** Overrides for tests. */
  read?: (assetId: string) => Promise<ProviderImage | null>;
  store?: (entityId: string, name: string, img: ProviderImage) => Promise<string>;
  service?: Db;
}

/** Returns null on success, or a short reason it failed. */
export async function runStoryboardJob(user: Db, jobId: string, deps: JobDeps): Promise<{ assetId?: string; error?: string }> {
  const service = deps.service ?? (supabaseService() as unknown as Db);
  const { data: claimed } = await service.rpc("storyboard_job_start", { p_job: jobId });
  if (!claimed) return { error: "This frame is already being made." };
  let usage: Record<string, unknown> | null = null;
  try {
    const { data: job } = await service.from("storyboard_jobs")
      .select("id, sequence_id, shot_id, kind, mode, prompt, params, reference_assets, base_asset_id").eq("id", jobId).single();
    if (!job) throw new Error("Job not found.");
    const { data: seq } = await service.from("storyboard_sequences").select("entity_id, title").eq("id", job.sequence_id).single();
    if (!seq) throw new Error("Storyboard not found.");
    const read = deps.read ?? ((id: string) => readAsset(service, id));
    const ids = [...(job.base_asset_id ? [job.base_asset_id as string] : []),
      ...((job.reference_assets as { asset_id: string }[]) ?? []).map((r) => r.asset_id)].slice(0, deps.provider.capabilities.referenceImages);
    const images: ProviderImage[] = [];
    for (const id of ids) {
      const img = await read(id);
      if (!img) throw new Error("A reference image couldn't be opened. Remove it or upload it again.");
      images.push(img);
    }
    const size = (job.params as { output?: { width: number; height: number } }).output ?? { width: 1536, height: 864 };
    const out = await deps.provider.generate({ prompt: job.prompt, width: size.width, height: size.height, images, quality: "medium" });
    usage = out.usage;
    const name = `${seq.title.replace(/[^A-Za-z0-9 _-]/g, "").slice(0, 60) || "storyboard"} ${job.mode === "look" ? "look" : "frame"}.png`;
    const store = deps.store ?? ((entityId: string, n: string, img: ProviderImage) => storeImage(user, service, entityId, n, img));
    const assetId = await store(seq.entity_id, name, out.image);
    const { error } = await service.rpc("storyboard_job_complete", { p_job: jobId, p_asset: assetId, p_usage: usage, p_model: out.model });
    if (error) throw new Error(error.message);
    return { assetId };
  } catch (e) {
    const message = e instanceof ProviderError || e instanceof Error ? e.message : "Something went wrong.";
    await service.rpc("storyboard_job_fail", { p_job: jobId, p_error: message.slice(0, 500), p_usage: usage });
    return { error: message };
  }
}
