// Publish VTracer (MIT OR Apache-2.0; classic raster → vector tracing, no AI) as a browser
// Web Worker: public/vendor/vtracer/{worker.js, vtracer_wasm_bg.wasm}. The npm package is
// built for Node (it reads the .wasm with fs); this rewrites only its loading tail so the
// same generated bindings fetch the .wasm in the browser. Run by `prebuild`.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const pkg = join("node_modules", "@visioncortex", "vtracer", "pkg");
const dst = join("public", "vendor", "vtracer");
mkdirSync(dst, { recursive: true });

let glue = readFileSync(join(pkg, "vtracer_wasm.js"), "utf8");
const tail = glue.indexOf("const wasmPath =");
if (tail < 0) throw new Error("VTracer's bindings changed shape; update scripts/build-vtracer-worker.mjs.");
glue = glue.slice(0, tail).replace(/^exports\.\w+ = \w+;$/gm, "");
if (/require\(|__dirname|exports\./.test(glue)) throw new Error("VTracer's bindings still reference Node APIs.");

const worker = `// GENERATED by scripts/build-vtracer-worker.mjs from @visioncortex/vtracer. Do not edit.
${glue}
let wasm;
const ready = (async () => {
  const bytes = await (await fetch(new URL("./vtracer_wasm_bg.wasm", self.location.href))).arrayBuffer();
  const { instance } = await WebAssembly.instantiate(bytes, __wbg_get_imports());
  wasm = instance.exports;
  wasm.__wbindgen_start();
})();
self.onmessage = async (e) => {
  try {
    await ready;
    const { rgba, width, height, options } = e.data;
    self.postMessage({ ok: true, svg: vectorize_rgba(new Uint8Array(rgba), width, height, options || {}) });
  } catch (err) {
    self.postMessage({ ok: false, error: String((err && err.message) || err) });
  }
};
`;
writeFileSync(join(dst, "worker.js"), worker);
copyFileSync(join(pkg, "vtracer_wasm_bg.wasm"), join(dst, "vtracer_wasm_bg.wasm"));
console.log("Published VTracer as a browser worker to public/vendor/vtracer/");
